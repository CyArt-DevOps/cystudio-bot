// avoid double-seeding: skip any question already present (by text)
const seen = new Set(bank.quests.map(q => q.q));
let added = 0;
const counts = {};
for (const [domain, list] of Object.entries(BANK)) {
  for (const item of list) {
    counts[`${domain}/${item.tier}`] = (counts[`${domain}/${item.tier}`] ?? 0) + 1;
    if (seen.has(item.q)) continue;
    bank.quests.push({
      id: bank.seq++, domain, tier: item.tier, q: item.q,
      hash: hash(item.a), reveal: item.a,
      hint: item.hint ?? null, explain: item.explain ?? null, ref: item.ref ?? null,
      qp: item.tier === 'hard' ? 25 : 10,
      status: 'queued', msgId: null, postedAt: null, solvers: [],
    });
    added++;
  }
}

